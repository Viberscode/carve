function parseRoadmapExercise(str) {
  const i = str.indexOf(" - ");
  let name = i === -1 ? str : str.slice(0, i);
  const dosage = i === -1 ? "" : str.slice(i + 3);
  // Remove bracket / parenthesis annotations from the title
  name = name.replace(/\s*[\(\[\{][^\)\]\}]*[\)\]\}]/g, "").replace(/\s{2,}/g, " ").trim();
  return { name, dosage };
}

function estimateSecondsFromDosage(dosage) {
  if (!dosage) return 30;
  const lower = dosage.toLowerCase();
  if (lower.includes("all day") || lower.includes("passive")) return 20;
  if (lower.includes("breath")) return 45;

  const minMatch = lower.match(/(\d+)\s*min/);
  if (minMatch) return Math.max(30, parseInt(minMatch[1], 10) * 60);

  const roundsMatch = lower.match(/(\d+)\s*rounds?/);
  const setsMatch = lower.match(/(\d+)\s*sets?/);
  const holdMatch = lower.match(/(\d+)\s*s\s*hold/);
  const timedMatch = lower.match(/(\d+)\s*s(?!\s*hold)/);
  const repsMatch = lower.match(/(\d+)\s*reps?/);
  const sets = setsMatch
    ? parseInt(setsMatch[1], 10)
    : roundsMatch
      ? parseInt(roundsMatch[1], 10)
      : 1;

  if (holdMatch) return Math.max(15, sets * parseInt(holdMatch[1], 10));
  if (timedMatch && (roundsMatch || setsMatch)) return Math.max(15, sets * parseInt(timedMatch[1], 10));
  if (repsMatch) return Math.max(15, sets * parseInt(repsMatch[1], 10) * 2);
  return 30;
}
